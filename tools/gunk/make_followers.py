"""Import the follower sprites from a pokeemerald-expansion checkout (graphics/pokemon/<species>/overworld*.png/.pal)
into graphics/gunk_followers/ and generate:

  src/data/gunk_followers.h      per-species frame tables and palettes, indexed by Ruby's species ids
  gunk_followers.mk               gbagfx rules (frames are 32x32 or 64x64 metatiles)

Usage: py -3 tools/gunk/make_followers.py <pokeemerald-expansion checkout>

The sprites are by the pokeemerald-expansion contributors (credited in README.md). Run once; the output is committed.
"""
import os
import re
import shutil
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = sys.argv[1]
OUT_GFX = os.path.join(ROOT, 'graphics', 'gunk_followers')


def png_size(path):
    w, h = struct.unpack('>II', open(path, 'rb').read(24)[16:24])
    return w, h


def main():
    os.makedirs(OUT_GFX, exist_ok=True)
    species = []
    for line in open(os.path.join(ROOT, 'include', 'constants', 'species.h')):
        m = re.match(r'#define SPECIES_(\w+)\s+(\d+)', line)
        if m:
            name, num = m.group(1), int(m.group(2))
            if num and not name.startswith('OLD_UNOWN') and name != 'EGG' and num <= 411:
                species.append((num, name))

    header = ['// Generated by tools/gunk/make_followers.py from pokeemerald-expansion\'s follower sprites. Do not edit.', '']
    table = []
    rules = ['# Generated by tools/gunk/make_followers.py. Do not edit.', '']
    for num, name in species:
        low = name.lower()
        src = os.path.join(SRC, 'graphics', 'pokemon', low)
        shutil.copyfile(os.path.join(src, 'overworld.png'), os.path.join(OUT_GFX, low + '.png'))
        shutil.copyfile(os.path.join(src, 'overworld_normal.pal'), os.path.join(OUT_GFX, low + '.pal'))
        shutil.copyfile(os.path.join(src, 'overworld_shiny.pal'), os.path.join(OUT_GFX, low + '_shiny.pal'))
        w, h = png_size(os.path.join(OUT_GFX, low + '.png'))
        big = h == 64
        frames = w // h
        cap = ''.join(p.capitalize() for p in low.split('_'))
        frame_bytes = h * h // 2
        rules.append(f'graphics/gunk_followers/{low}.4bpp: %.4bpp: %.png')
        rules.append(f'\t$(GBAGFX) $< $@ -mwidth {h // 8} -mheight {h // 8}')
        rules.append('')
        header.append(f'static const u8 sFollowerGfx_{cap}[] = INCBIN_U8("graphics/gunk_followers/{low}.4bpp");')
        header.append(f'static const u16 sFollowerPal_{cap}[] = INCBIN_U16("graphics/gunk_followers/{low}.gbapal");')
        header.append(f'static const u16 sFollowerShinyPal_{cap}[] = INCBIN_U16("graphics/gunk_followers/{low}_shiny.gbapal");')
        header.append(f'static const struct SpriteFrameImage sFollowerPics_{cap}[] = {{')
        for f in range(frames):
            header.append(f'    {{sFollowerGfx_{cap} + {f * frame_bytes}, {frame_bytes}}},')
        header.append('};')
        header.append('')
        table.append(f'    [SPECIES_{name}] = {{sFollowerPics_{cap}, sFollowerPal_{cap}, sFollowerShinyPal_{cap}, '
                     f'{"TRUE" if big else "FALSE"}, {"TRUE" if frames == 8 else "FALSE"}}},')
    header.append('static const struct GunkFollowerGfx sGunkFollowerGfx[] = {')
    header.extend(table)
    header.append('};')
    open(os.path.join(ROOT, 'src', 'data', 'gunk_followers.h'), 'w', newline='\n').write('\n'.join(header) + '\n')
    open(os.path.join(ROOT, 'gunk_followers.mk'), 'w', newline='\n').write('\n'.join(rules) + '\n')
    print(len(species), 'species')


if __name__ == '__main__':
    main()
